import { test } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { DatabaseSync } from 'node:sqlite';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { createHmac } from 'node:crypto';

test('hosted users, limits, proxy imports, admin allocation and revocation', async ()=>{
  const dir=await mkdtemp(join(tmpdir(),'kb-hosted-'));
  Object.assign(process.env,{KILO_BUSTER_TEST:'1',PROXY_STATE_FILE:join(dir,'state'),ADMIN_PASSWORD:'admin-test-only',DEFAULT_REQUESTS_PER_HOUR:'1'});
  const {handler,tokenDb}=await import('../server.mjs');
  const server=http.createServer(handler).listen(0,'127.0.0.1');
  await once(server,'listening');
  const origin='http://127.0.0.1:'+server.address().port;
  const realFetch=globalThis.fetch;
  const call=(url,body,headers={})=>realFetch(origin+url,{redirect:'manual',headers:{'Content-Type':'application/json',...headers},
    ...(body===undefined?{}:{method:'POST',body:JSON.stringify(body)})});
  try {
    assert.equal((await call('/healthz')).status,200);
    const dashboard=await call('/dashboard?token=old-secret');
    assert.equal(dashboard.headers.get('location'),'/admin');
    const login=await call('/portal/admin',{password:process.env.ADMIN_PASSWORD});
    const admin={cookie:login.headers.get('set-cookie').split(';')[0]};
    const identity={username:'tester',password:'test-password'};
    const signed=await call('/portal/register',identity);
    const member={cookie:signed.headers.get('set-cookie').split(';')[0]};
    assert.equal((await call('/portal/register',identity)).status,409);
    assert.equal((await call('/portal/login',identity)).status,200);
    assert.equal((await call('/portal/users',undefined,member)).status,403);
    assert.equal((await call('/portal/audit',undefined,member)).status,403);
    assert.equal((await call('/admin/monitoring',undefined,member)).status,403);
    const monitoring=await (await call('/admin/monitoring',undefined,admin)).json();
    assert.equal(monitoring.activeProxies,0);assert.equal(monitoring.welcomeFailed,0);assert.equal(monitoring.webhookFailures,0);
    assert.equal(monitoring.emailEnabled,true);
    assert.equal((await call('/admin/monitoring/email',{enabled:false},member)).status,403);
    assert.equal((await call('/admin/monitoring/email',{enabled:'false'},admin)).status,400);
    assert.equal((await call('/admin/monitoring/email',{enabled:false},admin)).status,200);
    assert.equal((await (await call('/admin/monitoring',undefined,admin)).json()).emailEnabled,false);
    assert.equal((await call('/admin/monitoring/email',{enabled:true},admin)).status,200);
    assert.equal((await (await call('/admin/monitoring',undefined,admin)).json()).emailEnabled,true);
    assert.equal((await call('/api/proxies/import',{},member)).status,403);
    assert.equal((await call('/api/proxies/import',{}, {...admin,origin:'https://elsewhere.invalid'})).status,403);
    const me=async()=> (await call('/portal/me',undefined,member)).json();
    const base='/portal/users/'+(await me()).id+'/';
    const issue=async quota=>({authorization:'Bearer '+(await (await call(base+'key',{quota},admin)).json()).key});
    assert.equal((await call('/portal/key',{},member)).status,403);
    assert.equal((await call(base+'key',{quota:100},member)).status,403);
    assert.equal((await me()).remaining,0);
    const newUser={username:'client',password:'private-client-pass',quota:24};
    assert.equal((await call('/portal/users/create-with-key',newUser,member)).status,403);
    const created=await (await call('/portal/users/create-with-key',newUser,admin)).json();
    assert.match(created.key,/^kb_/);
    assert.equal((await call('/api/admin/backup',{},member)).status,403);
    const snapshot=await call('/api/admin/backup',{},admin);
    assert.equal(snapshot.status,200);
    const restoredPath=join(dir,'restore-test.sqlite');await writeFile(restoredPath,Buffer.from(await snapshot.arrayBuffer()));
    const restored=new DatabaseSync(restoredPath);assert.equal(restored.prepare('SELECT username FROM users WHERE username=?').get('client').username,'client');restored.close();
    const audit=await (await call('/portal/audit',undefined,admin)).json();
    assert.ok(audit.some(entry=>entry.action==='create account and key'&&entry.target==='client'&&entry.detail.includes('24')));
    assert.ok(!JSON.stringify(audit).includes(created.key));
    assert.equal((await call('/portal/users/create-with-key',{...newUser,password:'different-pwd'},admin)).status,409);
    const clientLogin=await call('/portal/login',newUser);
    const clientHeaders={cookie:clientLogin.headers.get('set-cookie').split(';')[0]};
    const client=await (await call('/portal/me',undefined,clientHeaders)).json();
    assert.equal(client.keys.length,1);assert.equal(client.keys[0].quota,24);
    assert.equal(client.keys[0].suffix,created.key.slice(-6));
    await call('/portal/users/'+client.id+'/revoke',{},admin);
    const key=await issue(1);
    const chat=(headers)=>call('/v1/chat/completions',{messages:[]},headers);
    assert.equal((await chat(key)).status,503);
    assert.equal((await call('/health/stats',undefined,key)).status,403);
    globalThis.fetch=async()=>new Response('user:pass@example.com:8080\rhttp://user:pass@example.com:8080\rinvalid\rother.example:3128\r');
    assert.deepEqual(await (await call('/api/proxies/import',{},admin)).json(),{added:2,duplicates:1,invalid:1,total:2});
    assert.equal((await (await call('/api/proxies/import',{},admin)).json()).duplicates,3);
    globalThis.fetch=async()=>new Response(JSON.stringify({usage:{prompt_tokens:3,completion_tokens:2}}),{headers:{'content-encoding':'gzip','content-length':'999','connection':'keep-alive','keep-alive':'timeout=987'}});
    const results=await Promise.all([chat(key),chat(key)]);
    assert.deepEqual(results.map(r=>r.status).sort(),[200,429]);
    const forwarded=results.find(r=>r.status===200);
    assert.equal(forwarded.headers.get('content-encoding'),null);
    assert.notEqual(forwarded.headers.get('content-length'),'999');
    assert.notEqual(forwarded.headers.get('keep-alive'),'timeout=987');
    const u=await me();
    assert.deepEqual([u.total,u.used,u.remaining,u.input,u.output],[1,1,0,3,2]);
    const rotated=await issue(2);
    assert.equal((await chat(rotated)).status,200);
    assert.equal((await chat(key)).status,429);
    const [first,second]=(await me()).keys;
    assert.equal((await call('/portal/keys/'+first.id+'/delete',{},member)).status,403);
    assert.equal((await call('/portal/keys/'+first.id+'/delete',{},admin)).status,200);
    assert.equal((await chat(key)).status,401);
    assert.equal((await call('/portal/keys/'+second.id+'/quota',{quota:1},admin)).status,200);
    assert.equal((await chat(rotated)).status,429);
    assert.equal((await call('/portal/keys/'+second.id+'/quota',{quota:500},admin)).status,200);
    const allocation=async()=> (await call('/admin/allocation',undefined,admin)).json();
    const v=await allocation();
    assert.deepEqual([v.active,v.capacity,v.assigned,v.balance,v.remainingNow],[2,298,500,-202,296]);
    assert.equal((await chat(rotated)).status,200);
    tokenDb.prepare('UPDATE requests SET at=at-3600001').run();
    assert.equal((await me()).remaining,500);
    assert.equal((await me()).total,3);
    const request={rate:5000,email:'tester@example.com'};
    assert.equal((await call('/portal/usage-request',request)).status,403);
    assert.equal((await call('/portal/usage-request',{...request,rate:33},member)).status,400);
    process.env.RESEND_API_KEY='test';process.env.USAGE_EMAIL_FROM='demo@example.com';
    globalThis.fetch=async(url,opts)=>{
      assert.equal(url,'https://api.resend.com/emails');const msg=JSON.parse(opts.body);
      assert.deepEqual(msg.to,['aaronwise@aaronwiseai.com']);assert.equal(msg.reply_to,request.email);
      assert.match(msg.text,/tester/);assert.match(msg.text,/5000/);return Response.json({id:'fixture'});
    };
    assert.equal((await call('/portal/usage-request',request,member)).status,200);
    globalThis.fetch=async()=>new Response('',{status:403});
    assert.equal((await call('/portal/usage-request',request,member)).status,502);
    await call(base+'revoke',{},admin);
    assert.equal((await chat(rotated)).status,401);
    assert.equal((await call('/portal/me',undefined,member)).status,401);
    assert.equal((await call('/portal/login',identity)).status,401);
    assert.equal((await allocation()).assigned,0);
    await call(base+'enable',{},admin);
    assert.equal((await chat(rotated)).status,401);
    assert.equal((await call('/portal/login',identity)).status,200);
    const trial=await call('/portal/trial',{}), trialHeaders={cookie:trial.headers.get('set-cookie').split(';')[0]};
    const trialKey=(await trial.json()).key;
    assert.match(trialKey,/^kb_/);
    assert.equal((await (await call('/portal/trial/current',undefined,trialHeaders)).json()).key,trialKey);
    assert.equal((await (await call('/portal/trial',{},trialHeaders)).json()).key,trialKey);
    assert.deepEqual(await (await call('/portal/trial/current')).json(),{});
    Object.assign(process.env,{STRIPE_WEBHOOK_SECRET:'webhook-fixture',STRIPE_PRICE_2500:'price_fixture',STRIPE_SECRET_KEY:'sk_test_fixture'});
    const buyer=await call('/portal/register',{username:'subscriber',password:'private-test-pass'});
    const auth={cookie:buyer.headers.get('set-cookie').split(';')[0]};
    const uid=(await (await call('/portal/me',undefined,auth)).json()).id, now=Math.floor(Date.now()/1000);
    const event={type:'invoice.paid',created:now,livemode:false,data:{object:{id:'in_http',status:'paid',currency:'usd',amount_paid:799,customer:'cus_http',
      parent:{subscription_details:{subscription:'sub_http',metadata:{uid:String(uid)}}},lines:{data:[{amount:799,price:{id:'price_fixture'},period:{end:now+86400}}]}}}};
    const sig=createHmac('sha256',process.env.STRIPE_WEBHOOK_SECRET).update(now+'.'+JSON.stringify(event)).digest('hex');
    assert.equal((await call('/stripe/webhook',event)).status,400);
    assert.equal((await call('/stripe/webhook',event,{'stripe-signature':'t='+now+',v1='+sig})).status,200);
    const account=await (await call('/portal/me',undefined,auth)).json();
    assert.equal(account.keys.length,1);assert.equal(account.keys[0].quota,2500);assert.equal(account.invoices[0].amount,799);
    const before=(await (await call('/health/stats',undefined,admin)).json()).proxies;
    globalThis.fetch=async()=>new Response(JSON.stringify({code:'PROMOTION_MODEL_LIMIT_REACHED',message:'Sign up or come back later'}),{status:429,headers:{'content-type':'application/json'}});
    const limited=await chat({authorization:'Bearer '+account.keys[0].key});
    assert.equal(limited.status,429);assert.equal((await limited.json()).code,'PROMOTION_MODEL_LIMIT_REACHED');
    const after=(await (await call('/health/stats',undefined,admin)).json()).proxies;
    assert.equal(after.reduce((n,p)=>n+p.failures,0),before.reduce((n,p)=>n+p.failures,0)+2);
    assert.equal(after.reduce((n,p)=>n+p.successes,0),before.reduce((n,p)=>n+p.successes,0));
    assert.ok(after.some(p=>p.lastError.includes('Upstream rate limit')));
    assert.ok(after.every(p=>p.backoffSeconds>0));
    assert.equal((await call('/api/proxies/shuffle',{},member)).status,403);
    assert.equal((await call('/api/proxies/shuffle',{},admin)).status,200);
    assert.equal((await (await call('/portal/sales',undefined,admin)).json()).total.cents,799);
  } finally {
    globalThis.fetch=realFetch;
    await new Promise(done=>server.close(done));
    await new Promise(done=>setTimeout(done,150)); // flush the proxy health save timer
    tokenDb.close(); await rm(dir,{recursive:true,force:true});
  }
});
